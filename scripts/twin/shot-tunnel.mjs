import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 720 } })
p.on('pageerror', e => console.log('[pageerror]', String(e).slice(0, 200)))
await p.goto('http://localhost:3000', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(2500)
await p.getByRole('button', { name: 'Twin Villas', exact: false }).first().click()
await p.getByRole('button', { name: '▶ PLAY' }).click()
await p.waitForFunction(() => { const e = window.__eng; return e && e.state().map === 'twin' && e.state().tick > 40 }, undefined, { timeout: 90000 })
await p.waitForSelector('[data-loading]', { state: 'detached', timeout: 120000 })
await p.waitForTimeout(1500)
await p.evaluate(() => window.__eng.teleport(-6, -1.58, 0, -Math.PI / 2))
await p.waitForTimeout(600)
await p.screenshot({ path: 'scripts/twin/shots/t153-tunnel.png' })
console.log('shot tunnel done')
await b.close()
